import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { format, resolveConfig } from "prettier";
import type { Defect } from "../src/reporting/model.js";

interface Requirement {
  id: string;
  title: string;
  risk: string;
  tests: string[];
}

const ID = /\b(?:TC-[A-Z0-9]+-\d+|WB-\d+)\b/g;
const RANGE = /\b(TC-[A-Z0-9]+)-(\d+)\.\.(\d+)\b/g;
const DEFECT =
  /^\|\s*(DEF-\d+)\s*\|(?:\s*\[#\d+\]\((https:\/\/[^)\s]+)\)\s*\|)?\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|/gm;

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? entry.name === "unit"
        ? []
        : walk(join(dir, entry.name))
      : entry.name.endsWith(".spec.ts") || entry.name.endsWith(".feature")
        ? [join(dir, entry.name)]
        : [],
  );
}

export function collectTestIds(root: string): string[] {
  const ids = new Set<string>();
  for (const file of walk(root)) {
    const source = readFileSync(file, "utf8");
    for (const match of source.matchAll(ID)) {
      ids.add(match[0]);
    }
    // Data-driven tests generate their IDs; they declare them as `TC-E2E-010..014`.
    for (const [, prefix, from, to] of source.matchAll(RANGE)) {
      for (let n = Number(from); n <= Number(to); n += 1) {
        ids.add(`${prefix}-${String(n).padStart(from!.length, "0")}`);
      }
    }
  }
  return [...ids].toSorted();
}

export function collectDefectDetails(markdown: string): Defect[] {
  const defects = [...markdown.matchAll(DEFECT)].map((match) => ({
    id: match[1]!,
    title: match[3]!.trim(),
    severity: match[4]!.trim(),
    priority: match[5]!.trim(),
    tests: [...match[6]!.matchAll(ID)].map((id) => id[0]),
    status: match[7]!.trim(),
    ...(match[2] ? { issue: match[2] } : {}),
  }));
  const seen = new Set<string>();
  for (const defect of defects) {
    if (seen.has(defect.id)) throw new Error(`Duplicate defect: ${defect.id}`);
    if (defect.tests.length === 0) {
      throw new Error(`Defect ${defect.id} does not reference a test case.`);
    }
    seen.add(defect.id);
  }
  return defects;
}

export function collectDefects(markdown: string): Map<string, string> {
  return new Map(
    collectDefectDetails(markdown).map((defect) => [defect.id, defect.status]),
  );
}

export interface Trace {
  matrix: Map<string, string[]>;
  untraced: string[];
  uncovered: string[];
  ghostTests: string[];
}

/** Builds requirement -> tests; `ghostTests` are patterns that match no existing test. */
export function trace(requirements: Requirement[], ids: string[]): Trace {
  const matrix = new Map<string, string[]>();
  const ghostTests: string[] = [];
  for (const requirement of requirements) {
    const matched = new Set<string>();
    for (const pattern of requirement.tests) {
      const hits = ids.filter((id) => new RegExp(`^${pattern}$`).test(id));
      if (hits.length === 0) {
        ghostTests.push(`${requirement.id}: ${pattern}`);
      }
      for (const hit of hits) {
        matched.add(hit);
      }
    }
    matrix.set(requirement.id, [...matched].toSorted());
  }
  const covered = new Set([...matrix.values()].flat());
  return {
    matrix,
    untraced: ids.filter((id) => !covered.has(id)),
    uncovered: requirements
      .filter((r) => matrix.get(r.id)!.length === 0)
      .map((r) => r.id),
    ghostTests,
  };
}

function render(
  requirements: Requirement[],
  result: Trace,
  defects: Defect[],
  ids: string[],
): string {
  const rows = requirements.map((r) => {
    const tests = result.matrix.get(r.id)!;
    const linked = defects
      .filter((defect) => defect.tests.some((id) => tests.includes(id)))
      .map((defect) => defect.id);
    return `| ${r.id} | ${r.title} | ${r.risk} | ${tests.length} | ${tests.join(", ")} | ${linked.join(", ") || "—"} |`;
  });
  const defectRows = defects.map(
    (defect) =>
      `| ${defect.issue ? `[${defect.id}](${defect.issue})` : defect.id} | ${defect.severity} | ${defect.tests.join(", ")} | ${defect.status} |`,
  );
  return [
    "# Traceability matrix",
    "",
    "> Generated by `npm run traceability` from `requirements.json`, the `TC-*` identifiers in specs and Gherkin features, and the defect log. Do not edit by hand.",
    "",
    `Requirements: **${requirements.length}** · Test cases: **${ids.length}** · Defects: **${defects.length}**`,
    "",
    "| Requirement | Description | Risk | Tests | Test cases | Defects |",
    "| --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
    "## Defects",
    "",
    "| Defect | Severity | Test cases | Status |",
    "| --- | --- | --- | --- |",
    ...defectRows,
    "",
  ].join("\n");
}

if (
  import.meta.url === `file://${process.argv[1]?.replaceAll("\\", "/")}` ||
  process.argv[1]?.endsWith("build-traceability.ts")
) {
  const requirements = (
    JSON.parse(readFileSync("docs/test-management/requirements.json", "utf8")) as {
      requirements: Requirement[];
    }
  ).requirements;
  const ids = collectTestIds("tests");
  const defects = collectDefectDetails(
    readFileSync("docs/test-management/defect-log.md", "utf8"),
  );
  const result = trace(requirements, ids);

  const matrixPath = "docs/test-management/traceability-matrix.md";
  const markdown = await format(render(requirements, result, defects, ids), {
    ...(await resolveConfig(matrixPath)),
    filepath: matrixPath,
  });
  writeFileSync(matrixPath, markdown);
  writeFileSync(
    "reports/traceability.json",
    JSON.stringify(
      {
        requirements: Object.fromEntries(result.matrix),
        requirementDetails: requirements.map((requirement) => ({
          id: requirement.id,
          title: requirement.title,
          risk: requirement.risk,
          tests: result.matrix.get(requirement.id)!,
          defects: defects
            .filter((defect) =>
              defect.tests.some((id) => result.matrix.get(requirement.id)!.includes(id)),
            )
            .map((defect) => defect.id),
        })),
        defects: Object.fromEntries(defects.map((defect) => [defect.id, defect.status])),
        defectDetails: defects,
        ...result,
        matrix: undefined,
      },
      null,
      2,
    ),
  );

  const problems = [
    ...result.untraced.map((id) => `Test ${id} is not linked to any requirement`),
    ...result.uncovered.map((id) => `Requirement ${id} has no tests`),
    ...result.ghostTests.map((entry) => `Pattern without tests: ${entry}`),
    ...defects.flatMap((defect) =>
      defect.tests
        .filter((id) => !ids.includes(id))
        .map((id) => `Defect ${defect.id} references unknown test ${id}`),
    ),
  ];
  if (problems.length > 0) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  console.log(
    `Traceability OK: ${ids.length} tests, ${requirements.length} requirements.`,
  );
}
