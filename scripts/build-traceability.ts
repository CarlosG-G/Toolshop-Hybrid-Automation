import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface Requirement {
  id: string;
  title: string;
  risk: string;
  tests: string[];
}

const ID = /\b(?:TC-[A-Z0-9]+-\d+|WB-\d+)\b/g;
const RANGE = /\b(TC-[A-Z0-9]+)-(\d+)\.\.(\d+)\b/g;
const DEFECT = /^\|\s*(DEF-\d+)\s*\|[^|]*\|[^|]*\|[^|]*\|[^|]*\|\s*([^|]+?)\s*\|/gm;

function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory()
      ? entry.name === "unit"
        ? []
        : walk(join(dir, entry.name))
      : entry.name.endsWith(".spec.ts")
        ? [join(dir, entry.name)]
        : [],
  );
}

export function collectTestIds(root: string): string[] {
  const ids = new Set<string>();
  for (const file of walk(root)) {
    const source = readFileSync(file, "utf8");
    for (const match of source.matchAll(ID)) {
      ids.add(match[0]);
    }
    // Data-driven tests generate their IDs; they declare them as `TC-E2E-010..014`.
    for (const [, prefix, from, to] of source.matchAll(RANGE)) {
      for (let n = Number(from); n <= Number(to); n += 1) {
        ids.add(`${prefix}-${String(n).padStart(from!.length, "0")}`);
      }
    }
  }
  return [...ids].toSorted();
}

export function collectDefects(markdown: string): Map<string, string> {
  return new Map([...markdown.matchAll(DEFECT)].map((m) => [m[1]!, m[2]!]));
}

export interface Trace {
  matrix: Map<string, string[]>;
  untraced: string[];
  uncovered: string[];
  ghostTests: string[];
}

/** Builds requirement -> tests; `ghostTests` are patterns that match no existing test. */
export function trace(requirements: Requirement[], ids: string[]): Trace {
  const matrix = new Map<string, string[]>();
  const ghostTests: string[] = [];
  for (const requirement of requirements) {
    const matched = new Set<string>();
    for (const pattern of requirement.tests) {
      const hits = ids.filter((id) => new RegExp(`^${pattern}$`).test(id));
      if (hits.length === 0) {
        ghostTests.push(`${requirement.id}: ${pattern}`);
      }
      for (const hit of hits) {
        matched.add(hit);
      }
    }
    matrix.set(requirement.id, [...matched].toSorted());
  }
  const covered = new Set([...matrix.values()].flat());
  return {
    matrix,
    untraced: ids.filter((id) => !covered.has(id)),
    uncovered: requirements
      .filter((r) => matrix.get(r.id)!.length === 0)
      .map((r) => r.id),
    ghostTests,
  };
}

function render(
  requirements: Requirement[],
  result: Trace,
  defects: Map<string, string>,
  ids: string[],
): string {
  const rows = requirements.map((r) => {
    const tests = result.matrix.get(r.id)!;
    return `| ${r.id} | ${r.title} | ${r.risk} | ${tests.length} | ${tests.join(", ")} |`;
  });
  const defectRows = [...defects].map(([id, status]) => `| ${id} | ${status} |`);
  return [
    "# Traceability matrix",
    "",
    "> Generated by `npm run traceability` from `requirements.json`, the `TC-*` identifiers in `tests/` and the defect log. Do not edit by hand.",
    "",
    `Requirements: **${requirements.length}** · Test cases: **${ids.length}** · Defects: **${defects.size}**`,
    "",
    "| Requirement | Description | Risk | Tests | Test cases |",
    "| --- | --- | --- | --- | --- |",
    ...rows,
    "",
    "## Defects",
    "",
    "| Defect | Status |",
    "| --- | --- |",
    ...defectRows,
    "",
  ].join("\n");
}

if (
  import.meta.url === `file://${process.argv[1]?.replaceAll("\\", "/")}` ||
  process.argv[1]?.endsWith("build-traceability.ts")
) {
  const requirements = (
    JSON.parse(readFileSync("docs/test-management/requirements.json", "utf8")) as {
      requirements: Requirement[];
    }
  ).requirements;
  const ids = collectTestIds("tests");
  const defects = collectDefects(
    readFileSync("docs/test-management/defect-log.md", "utf8"),
  );
  const result = trace(requirements, ids);

  const markdown = render(requirements, result, defects, ids);
  writeFileSync("docs/test-management/traceability-matrix.md", markdown);
  writeFileSync(
    "reports/traceability.json",
    JSON.stringify(
      {
        requirements: Object.fromEntries(result.matrix),
        defects: Object.fromEntries(defects),
        ...result,
        matrix: undefined,
      },
      null,
      2,
    ),
  );

  const problems = [
    ...result.untraced.map((id) => `Test ${id} is not linked to any requirement`),
    ...result.uncovered.map((id) => `Requirement ${id} has no tests`),
    ...result.ghostTests.map((entry) => `Pattern without tests: ${entry}`),
  ];
  if (problems.length > 0) {
    console.error(problems.join("\n"));
    process.exit(1);
  }
  console.log(
    `Traceability OK: ${ids.length} tests, ${requirements.length} requirements.`,
  );
}
